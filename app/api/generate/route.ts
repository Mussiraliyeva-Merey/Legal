export async function POST(req: Request) {
  try {
    const apiKey = process.env.GEMINI_API_KEY

    if (!apiKey) {
      return Response.json(
        { error: 'Сервис временно недоступен. Попробуйте позже.' },
        { status: 503 },
      )
    }

    const body: GenerateRequest = await req.json()
    const prompt = buildPrompt(body)

    const controller = new AbortController()
    const timeout = setTimeout(() => controller.abort(), 55000)

    let geminiResponse: Response
    try {
      geminiResponse = await fetch(
        `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.0-flash:generateContent?key=${apiKey}`,
        {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            contents: [
              {
                parts: [
                  { text: `${SYSTEM_PROMPT}\n\n${LANG_INSTRUCTION}\n\n${prompt}` },
                ],
              },
            ],
            generationConfig: {
              temperature: 0.4,
              maxOutputTokens: 8192,
            },
          }),
          signal: controller.signal,
        },
      )
    } catch (fetchErr) {
      clearTimeout(timeout)
      if ((fetchErr as Error).name === 'AbortError') {
        return Response.json(
          { error: 'Время ожидания истекло. Попробуйте ещё раз.' },
          { status: 504 },
        )
      }
      throw fetchErr
    }
    clearTimeout(timeout)

    if (!geminiResponse.ok) {
      const errorText = await geminiResponse.text().catch(() => '')
      if (geminiResponse.status === 429) {
        return Response.json(
          { error: 'Сервис перегружен. Попробуйте через минуту.' },
          { status: 429 },
        )
      }
      console.error('[gemini] error:', geminiResponse.status, errorText)
      return Response.json(
        { error: 'Не удалось сформировать претензию. Попробуйте ещё раз.' },
        { status: 502 },
      )
    }

    const geminiData = await geminiResponse.json()
    const text =
      geminiData?.candidates?.[0]?.content?.parts?.[0]?.text ??
      geminiData?.candidates?.[0]?.content?.parts?.map((p: { text?: string }) => p.text).join('') ??
      ''

    if (!text || text.trim().length === 0) {
      return Response.json(
        { error: 'Получен пустой ответ. Попробуйте переформулировать описание.' },
        { status: 502 },
      )
    }

    return Response.json({ claim: text })
  } catch (err) {
    console.error('[generate] error:', (err as Error).message)
    return Response.json(
      { error: 'Произошла ошибка при генерации. Попробуйте ещё раз.' },
      { status: 500 },
    )
  }
}
